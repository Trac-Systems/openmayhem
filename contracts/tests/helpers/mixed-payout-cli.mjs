import assert from 'node:assert/strict';
import http from 'node:http';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const ROOT = fileURLToPath(new URL('../../..', import.meta.url));
const listen = server => new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const close = server => new Promise(resolve => { server.closeAllConnections(); server.close(resolve); });

/** Exercise the actual CLI with the same option set as the production wrapper.
 * Both RPC transports are isolated loopback fixtures; all Ethereum signing
 * identities are generated by Ganache for this test and never written/logged. */
export async function checkBundledCli(t, f, chain, pool, token, owner, governanceWallet, treasury) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'mayhem-mixed-tap-cli-')); fs.chmodSync(root, 0o700);
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const eth = http.createServer(async (request, response) => {
    try {
      const chunks = []; for await (const chunk of request) chunks.push(chunk);
      const input = JSON.parse(Buffer.concat(chunks));
      const call = async value => {
        try { return { jsonrpc: '2.0', id: value.id, result: await chain.request({ method: value.method, params: value.params }) }; }
        catch (error) { return { jsonrpc: '2.0', id: value.id, error: { code: error.code ?? -32000, message: error.message, data: error.data } }; }
      };
      response.setHeader('content-type', 'application/json');
      response.end(JSON.stringify(Array.isArray(input) ? await Promise.all(input.map(call)) : await call(input)));
    } catch { response.writeHead(400); response.end(); }
  });
  await listen(eth); t.after(() => close(eth));
  const payment = { denom: 'au_usd', ver: 1, set_by: f.f.admin.publicKey, set_by_role: 'admin',
    tap: { chain_id: 1, token_address: await token.getAddress(), pool_address: await pool.getAddress() } };
  const fixtureReads = new Map([
    ['payments/current', payment], ['epoch/apply/state', { updated_epoch: f.epoch + 1000 }],
    ['params/challenge_epochs', { current: { value: 6, effective_at: 0 }, pending: null }],
    ['params/payout_min_au', { key: 'payout_min_au', current: { value: f.args.payoutMinAu, effective_at: 0, ver: 1 }, pending: null }],
    ['tap/rate/latest', { denom: 'tap_usd_au', tap_usd_au: f.args.tapUsdAu, source: 'isolated-fixed-rate', ts: f.epoch * 3600,
      updated_at: `rate/tap/${f.epoch * 3600}/${'e'.repeat(64)}`, posted_by: f.f.admin.publicKey, posted_by_role: 'admin' }],
  ]);
  const ledger = http.createServer(async (request, response) => {
    const url = new URL(request.url, 'http://127.0.0.1');
    if (request.method !== 'GET' || url.pathname !== '/v1/state') { response.writeHead(405); response.end(); return; }
    const key = url.searchParams.get('key');
    const value = fixtureReads.has(key) ? fixtureReads.get(key) : await f.f.read(key);
    response.setHeader('content-type', 'application/json');
    response.end(JSON.stringify({ key, confirmed: true, signed_length: 44, value }));
  });
  await listen(ledger); t.after(() => close(ledger));
  const bundle = path.join(root, 'bundle.json'); fs.writeFileSync(bundle, JSON.stringify(f.bundle), { mode: 0o600 });
  const options = { '--bundle': bundle, '--tap-rate-lock': path.join(root, 'rate.json'), '--ledger-fee-bps': '1500',
    '--peer-rpc': `http://127.0.0.1:${ledger.address().port}/v1`, '--eth-rpc': `http://127.0.0.1:${eth.address().port}`,
    '--pool': await pool.getAddress(), '--operator-address': await treasury.getAddress(), '--json': null };
  const wrapper = fs.readFileSync(path.join(ROOT, 'scripts/ops/run-tap-settlement-roller.sh'), 'utf8');
  const wrapperOptions = [...wrapper.match(/  args=\([\s\S]*?\n  \)/)[0].matchAll(/^    (--[a-z-]+)/gm)].map(match => match[1]);
  assert.deepEqual(wrapperOptions, Object.keys(options));
  assert.ok(!wrapperOptions.includes('--epoch'), 'canonical bundle must own the default through the actual wrapper');
  const args = [path.join(ROOT, 'contracts/scripts/tap-settlement-roller.mjs'), ...Object.entries(options).flatMap(([key, value]) => value === null ? [key] : [key, value])];
  const accounts = chain.getInitialAccounts();
  const ownerKey = accounts[(await owner.getAddress()).toLowerCase()].secretKey;
  const env = { PATH: '/usr/bin:/bin', HOME: root, LANG: 'C', MAYHEM_TAP_ROLLER_PRIVATE_KEY: ownerKey,
    MAYHEM_TAP_GOVERNANCE_PRIVATE_KEY: governanceWallet.privateKey };
  const run = extra => new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [...args, ...extra], { cwd: ROOT, env, stdio: ['ignore', 'pipe', 'pipe'] });
    let stdout = '', stderr = ''; const timer = setTimeout(() => child.kill('SIGKILL'), 20_000);
    child.stdout.on('data', data => { stdout += data; if (stdout.length > 1024 * 1024) child.kill('SIGKILL'); });
    child.stderr.on('data', data => { stderr += data; if (stderr.length > 64 * 1024) child.kill('SIGKILL'); });
    child.on('error', error => { clearTimeout(timer); reject(error); });
    child.on('close', status => { clearTimeout(timer); resolve({ status, stdout, stderr }); });
  });
  const result = await run([]); assert.equal(result.status, 0, result.stderr);
  const report = JSON.parse(result.stdout);
  assert.equal(report.epoch, f.epoch); assert.equal(report.tap_rate_lock.epoch, f.epoch);
  assert.equal(report.propose_root_dry_run.ok, true); assert.equal(report.posted, false);
  assert.equal(report.receipt_count, 2); assert.equal(await pool.epoch(), 0n);
  assert.match(report.copy_paste_replay_command, /'--epoch' '101'/);
  const conflict = await run(['--epoch', '1']); assert.notEqual(conflict.status, 0);
  assert.match(conflict.stderr, /epoch conflicts/); assert.equal(await pool.epoch(), 0n);
  return report;
}
