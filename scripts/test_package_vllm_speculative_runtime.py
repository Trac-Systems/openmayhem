SPEC = importlib.util.spec_from_file_location(
    "packager", Path(__file__).with_name("package-vllm-speculative-runtime.py"))
p = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(p)

OLD = b"# synthetic original backend\n"
NEW = b"# synthetic fixed backend\n"
VERSION_SOURCE = b'''# file generated by vcs-versioning\nfrom __future__ import annotations
__all__ = ["__version__", "__version_tuple__", "version", "version_tuple", "__commit_id__", "commit_id"]
__version__: str
version: str
__version_tuple__: tuple[int | str, ...]
version_tuple: tuple[int | str, ...]
__commit_id__: str | None
commit_id: str | None
__version__ = version = '0.24.0'
__version_tuple__ = version_tuple = (0, 24, 0)
__commit_id__ = commit_id = 'gee0da84ab'
'''


class PackagerTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.wheel = self.root / next(iter(p.UPSTREAM_HASHES))
        self.output = self.root / "output"
        self.patches = mock.patch.multiple(
            p, OLD_BACKEND_SHA=p.sha256(OLD), NEW_BACKEND_SHA=p.sha256(NEW))
        self.patches.start()
        self.addCleanup(self.patches.stop)

    def fixture(self, changes=None, extra=(), record_edit=None):
        tag = p.UPSTREAM_WHEEL_TAGS[self.wheel.name][0]
        members = {
            p.BACKEND: OLD,
            p.VERSION_FILE: VERSION_SOURCE,
            p.DIST + "/METADATA": (
                b"Metadata-Version: 2.4\r\nName: vllm\r\nVersion: 0.24.0\r\n"
                b"Requires-Dist: torch==2.11.0\r\nRequires-Dist: example;\r\n"
                b" python_version >= '3.8'\r\nLicense-Expression: Apache-2.0\r\n"
                b"\r\nDescription\r\nVersion: not a header\r\n"),
            p.DIST + "/WHEEL": ("Wheel-Version: 1.0\nGenerator: fixture\n"
                                  "Root-Is-Purelib: false\nTag: " + tag + "\n").encode(),
            p.DIST + "/licenses/LICENSE": b"untouched license\n",
            "vllm/_C.abi3.so": bytes(range(256)) * 10000,
            "vllm/unchanged.py": b"raise RuntimeError('must never execute')\n",
            p.DIST + "/": b"",
        }
        members.update(changes or {})
        entries = list(members.items()) + list(extra)
        rows = [(n, p.record_hash(p.sha256(d)), str(len(d)))
                for n, d in entries if not n.endswith("/")]
        rows.append((p.RECORD, "", ""))
        if record_edit:
            record_edit(rows)
        record = io.StringIO(newline="")
        csv.writer(record, lineterminator="\n").writerows(rows)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", UserWarning)
            with zipfile.ZipFile(self.wheel, "w", zipfile.ZIP_DEFLATED) as wheel:
                for name, data in entries:
                    wheel.writestr(name, data)
                wheel.writestr(p.RECORD, record.getvalue().encode())
        return members

    def run_package(self, output=None):
        return p._package(self.wheel, output or self.output, NEW,
                          p.sha256(self.wheel.read_bytes()))

    def assert_rejected(self, pattern=None):
        with self.assertRaisesRegex((p.InvalidWheel, zipfile.BadZipFile, ValueError), pattern or "."):
            self.run_package()
        if self.output.exists():
            self.assertEqual(list(self.output.iterdir()), [])

    def test_deterministic_rewrite_and_complete_record(self):
        for name in p.UPSTREAM_HASHES:
            with self.subTest(name=name):
                self.wheel = self.root / name
                members = self.fixture()
                first, provenance_path = self.run_package(self.root / (name + "-a"))
                second, second_provenance = self.run_package(self.root / (name + "-b"))
                self.assertEqual(first.read_bytes(), second.read_bytes())
                self.assertEqual(provenance_path.read_bytes(), second_provenance.read_bytes())
                provenance = json.loads(provenance_path.read_bytes())
                self.assertEqual(provenance["output_wheel"]["sha256"], p.sha256(first.read_bytes()))
                self.assertEqual(provenance["base_commit"], p.BASE_COMMIT)
                self.assertEqual(provenance["fix_commit"], p.FIX_COMMIT)
                with zipfile.ZipFile(first) as result:
                    expected_names = {p.renamed(n) for n in members} | {p.renamed(p.RECORD)}
                    self.assertEqual(set(result.namelist()), expected_names)
                    for member, data in members.items():
                        if member not in (p.BACKEND, p.VERSION_FILE, p.DIST + "/METADATA"):
                            self.assertEqual(result.read(p.renamed(member)), data)
                    self.assertEqual(result.read(p.BACKEND), NEW)
                    version = ast.parse(result.read(p.VERSION_FILE))
                    values = {node.targets[0].id: ast.literal_eval(node.value)
                              for node in version.body if isinstance(node, ast.Assign)}
                    self.assertEqual(values["__version__"], p.VERSION)
                    self.assertEqual(values["__version_tuple__"], (0, 24, 0, "mayhem.specmeta1"))
                    self.assertEqual(values["__commit_id__"], "g" + p.FIX_COMMIT[:9])
                    self.assertEqual(result.read(p.NEW_DIST + "/METADATA"),
                                     members[p.DIST + "/METADATA"].replace(
                                         b"Version: 0.24.0\r\n", b"Version: " + p.VERSION.encode() + b"\r\n"))
                    record = list(csv.reader(io.StringIO(result.read(p.renamed(p.RECORD)).decode())))
                    self.assertEqual({r[0] for r in record},
                                     {n for n in expected_names if not n.endswith("/")})
                    for member, digest, size in record:
                        data = result.read(member)
                        if member == p.renamed(p.RECORD):
                            self.assertEqual((digest, size), ("", ""))
                        else:
                            self.assertEqual((digest, size), (p.record_hash(p.sha256(data)), str(len(data))))
                    self.assertTrue(all(i.date_time == (1980, 1, 1, 0, 0, 0)
                                        and i.compress_type == zipfile.ZIP_STORED
                                        for i in result.infolist()))
                changed = {row["original"] for row in provenance["changed_members"]}
                self.assertEqual(changed, {p.BACKEND, p.VERSION_FILE, p.RECORD} |
                                 {n for n in members if n.startswith(p.DIST + "/")})

    def test_production_hash_gate_has_no_fixture_override(self):
        self.fixture()
        with mock.patch.object(p, "fixed_source", return_value=NEW):
            with self.assertRaisesRegex(p.InvalidWheel, "upstream wheel SHA256"):
                p.package(self.wheel, self.root, self.output)
        self.assertFalse(self.output.exists())
        self.assertEqual(len(p.UPSTREAM_HASHES), 2)

    def test_pinned_internal_linux_tags_are_preserved(self):
        for arch, other in (("aarch64", "x86_64"), ("x86_64", "aarch64")):
            with self.subTest(architecture=arch):
                self.wheel = self.root / ("vllm-0.24.0-cp38-abi3-manylinux_2_28_" + arch + ".whl")
                self.output = self.root / arch
                tag = ("cp38-abi3-linux_" + arch).encode()
                metadata = (b"Wheel-Version: 1.0\nGenerator: setuptools (80.10.2)\n"
                            b"Root-Is-Purelib: false\nTag: " + tag + b"\n")
                self.fixture({p.DIST + "/WHEEL": metadata})
                output, _ = self.run_package()
                with zipfile.ZipFile(output) as wheel:
                    self.assertEqual(wheel.read(p.NEW_DIST + "/WHEEL"), metadata)
                self.output = self.root / (arch + "-rejected")
                for wrong in ("cp38-abi3-manylinux_2_28_" + arch, "cp38-abi3-linux_" + other):
                    self.fixture({p.DIST + "/WHEEL": metadata.replace(tag, wrong.encode())})
                    self.assert_rejected("unknown original WHEEL metadata")

