    def test_no_overwrite_and_cleanup_publication_race(self):
        self.fixture()
        wheel, sidecar = self.run_package()
        saved = (wheel.read_bytes(), sidecar.read_bytes())
        with self.assertRaisesRegex(p.InvalidWheel, "output already exists"):
            self.run_package()
        self.assertEqual((wheel.read_bytes(), sidecar.read_bytes()), saved)
        wheel.unlink()
        sidecar.unlink()
        real_link = p.os.link

        def race(source, destination):
            if str(destination).endswith(".json"):
                Path(destination).write_bytes(b"other owner")
            real_link(source, destination)

        with mock.patch.object(p.os, "link", side_effect=race):
            with self.assertRaises(FileExistsError):
                self.run_package()
        self.assertFalse(wheel.exists())
        self.assertEqual(sidecar.read_bytes(), b"other owner")
        self.assertEqual(list(self.output.iterdir()), [sidecar])

    def test_large_members_are_streamed(self):
        self.fixture()
        original_read = zipfile.ZipExtFile.read

        def bounded_read(stream, size=-1):
            if stream.name.endswith(".so"):
                self.assertGreater(size, 0)
                self.assertLessEqual(size, p.CHUNK)
            return original_read(stream, size)

        with mock.patch.object(zipfile.ZipExtFile, "read", bounded_read):
            self.run_package()

    def test_minimal_export_source_and_pinned_identity(self):
        source = self.root / "source"
        backend = source / p.BACKEND
        backend.parent.mkdir(parents=True)
        backend.write_bytes(NEW)
        manifest = source / "vllm-specmeta-source.json"
        identity = {"base_commit": p.BASE_COMMIT, "fix_commit": p.FIX_COMMIT,
                    "backend_sha256": p.NEW_BACKEND_SHA}
        manifest.write_text(json.dumps(identity))
        with mock.patch.object(p, "git", side_effect=AssertionError("no git for export")):
            self.assertEqual(p.fixed_source(source), NEW)
        for key in identity:
            manifest.write_text(json.dumps({**identity, key: "wrong"}))
            with self.assertRaisesRegex(p.InvalidWheel, "identity mismatch"):
                p.fixed_source(source)
        manifest.write_text(json.dumps(identity))
        backend.write_bytes(OLD)
        with self.assertRaisesRegex(p.InvalidWheel, "backend SHA256"):
            p.fixed_source(source)

    def test_sparse_git_source_identity_and_index(self):
        source = self.root / "source"
        backend = source / p.BACKEND
        backend.parent.mkdir(parents=True)
        backend.write_bytes(NEW)
        (source / ".git").mkdir()
        blob = p.hashlib.sha1(b"blob " + str(len(NEW)).encode() + b"\0" + NEW).hexdigest().encode()
        replies = [p.FIX_COMMIT.encode(), p.BASE_COMMIT.encode(),
                   b"100644 blob " + blob + b"\t" + p.BACKEND.encode() + b"\0",
                   b"100644 " + blob + b" 0\t" + p.BACKEND.encode() + b"\0"]
        for mode in (b"100644", b"100755"):
            for local_mode in (0o644, 0o755):
                backend.chmod(local_mode)
                matching = [row.replace(b"100644", mode) for row in replies]
                with self.subTest(git_mode=mode, local_mode=local_mode):
                    with mock.patch.object(p, "git", side_effect=matching):
                        self.assertEqual(p.fixed_source(source), NEW)
        mismatched_index = replies.copy()
        mismatched_index[-1] = mismatched_index[-1].replace(b"100644", b"100755")
        with mock.patch.object(p, "git", side_effect=mismatched_index):
            with self.assertRaisesRegex(p.InvalidWheel, "index is not clean"):
                p.fixed_source(source)
        for i in range(len(replies)):
            changed = replies.copy()
            changed[i] = b"wrong"
            with mock.patch.object(p, "git", side_effect=changed):
                with self.assertRaises(p.InvalidWheel):
                    p.fixed_source(source)


