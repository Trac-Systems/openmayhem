    def test_record_hash_size_coverage_and_duplicates(self):
        edits = [
            lambda rows: rows.__setitem__(0, (rows[0][0], p.record_hash("00" * 32), rows[0][2])),
            lambda rows: rows.__setitem__(0, (rows[0][0], rows[0][1], "999")),
            lambda rows: rows.pop(0),
            lambda rows: rows.append(rows[0]),
            lambda rows: rows.append(("ghost", "", "")),
            lambda rows: rows.__setitem__(-1, (p.RECORD, "sha256=bad", "0")),
            lambda rows: rows.__setitem__(0, (rows[0][0], "", rows[0][2])),
        ]
        for edit in edits:
            self.fixture(record_edit=edit)
            self.assert_rejected()

    def test_streamed_binary_hash_failure_cleans_owned_temps(self):
        def corrupt(rows):
            for i, row in enumerate(rows):
                if row[0].endswith(".so"):
                    rows[i] = (row[0], p.record_hash("00" * 32), row[2])
        self.fixture(record_edit=corrupt)
        self.assert_rejected("RECORD hash/size mismatch")

